extern float res4_3;
extern float res5_0;
extern float res5_1;
extern float res5_2;
extern float res5_3;
extern float res6_0;
extern float res6_1;
extern float res6_2;
extern float res6_3;
extern float res7_0;
extern float res7_1;
extern float res7_2;
extern float res7_3;
extern float a0;
extern float a1;
extern float b0;
extern float b1;
extern float b2;
extern float b3;
extern float b4;
extern float b5;
extern float b6;
extern float b7;
extern BLASLONG off;
extern BLASLONG temp;
extern _Bool left;
extern _Bool backwards;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
for (j = 0; j < bn / 8; j += 1) {
    C0 = C;
    C1 = C0 + ldc;
    C2 = C1 + ldc;
    C3 = C2 + ldc;
    C4 = C3 + ldc;
    C5 = C4 + ldc;
    C6 = C5 + ldc;
    C7 = C6 + ldc;
    if (left) {
        off = offset;
    }
    ptrba = ba;
    for (i = 0; i < bm / 4; i += 1) {
        ptrbb = bb;
        if (backwards) {
            ptrba += off * 4;
            ptrbb += off * 8;
        }
        res0_0 = 0;
        res0_1 = 0;
        res0_2 = 0;
        res0_3 = 0;
        res1_0 = 0;
        res1_1 = 0;
        res1_2 = 0;
        res1_3 = 0;
        res2_0 = 0;
        res2_1 = 0;
        res2_2 = 0;
        res2_3 = 0;
        res3_0 = 0;
        res3_1 = 0;
        res3_2 = 0;
        res3_3 = 0;
        res4_0 = 0;
        res4_1 = 0;
        res4_2 = 0;
        res4_3 = 0;
        res5_0 = 0;
        res5_1 = 0;
        res5_2 = 0;
        res5_3 = 0;
        res6_0 = 0;
        res6_1 = 0;
        res6_2 = 0;
        res6_3 = 0;
        res7_0 = 0;
        res7_1 = 0;
        res7_2 = 0;
        res7_3 = 0;
        temp = backwards ? bk - off : left ? off + 4 : off + 8;
        for (k = 0; k < temp; k++) {
            b0 = ptrbb[0];
            b1 = ptrbb[1];
            b2 = ptrbb[2];
            b3 = ptrbb[3];
            b4 = ptrbb[4];
            b5 = ptrbb[5];
            b6 = ptrbb[6];
            b7 = ptrbb[7];
            a0 = ptrba[0];
            a1 = ptrba[1];
            float t0 = a0 * b0, t1 = a0 * b1, t2 = a0 * b2, t3 = a0 * b3;
            float t4 = a0 * b4, t5 = a0 * b5, t6 = a0 * b6, t7 = a0 * b7;
            res0_0 += t0;
            res1_0 += t1;
            res2_0 += t2;
            res3_0 += t3;
            res4_0 += t4;
            res5_0 += t5;
            res6_0 += t6;
            res7_0 += t7;
            res0_1 += a1 * b0;
            res1_1 += a1 * b1;
            res2_1 += a1 * b2;
            res3_1 += a1 * b3;
            res4_1 += a1 * b4;
            res5_1 += a1 * b5;
            res6_1 += a1 * b6;
            res7_1 += a1 * b7;
            a0 = ptrba[2];
            a1 = ptrba[3];
            res0_2 += a0 * b0;
            res1_2 += a0 * b1;
            res2_2 += a0 * b2;
            res3_2 += a0 * b3;
            res4_2 += a0 * b4;
            res5_2 += a0 * b5;
            res6_2 += a0 * b6;
            res7_2 += a0 * b7;
            res0_3 += a1 * b0;
            res1_3 += a1 * b1;
            res2_3 += a1 * b2;
            res3_3 += a1 * b3;
            res4_3 += a1 * b4;
            res5_3 += a1 * b5;
            res6_3 += a1 * b6;
            res7_3 += a1 * b7;
            ptrba = ptrba + 4;
            ptrbb = ptrbb + 8;
        }
        res0_0 *= alpha;
        res0_1 *= alpha;
        res0_2 *= alpha;
        res0_3 *= alpha;
        res1_0 *= alpha;
        res1_1 *= alpha;
        res1_2 *= alpha;
        res1_3 *= alpha;
        res2_0 *= alpha;
        res2_1 *= alpha;
        res2_2 *= alpha;
        res2_3 *= alpha;
        res3_0 *= alpha;
        res3_1 *= alpha;
        res3_2 *= alpha;
        res3_3 *= alpha;
        res4_0 *= alpha;
        res4_1 *= alpha;
        res4_2 *= alpha;
        res4_3 *= alpha;
        res5_0 *= alpha;
        res5_1 *= alpha;
        res5_2 *= alpha;
        res5_3 *= alpha;
        res6_0 *= alpha;
        res6_1 *= alpha;
        res6_2 *= alpha;
        res6_3 *= alpha;
        res7_0 *= alpha;
        res7_1 *= alpha;
        res7_2 *= alpha;
        res7_3 *= alpha;
        C0[0] = res0_0;
        C0[1] = res0_1;
        C0[2] = res0_2;
        C0[3] = res0_3;
        C1[0] = res1_0;
        C1[1] = res1_1;
        C1[2] = res1_2;
        C1[3] = res1_3;
        C2[0] = res2_0;
        C2[1] = res2_1;
        C2[2] = res2_2;
        C2[3] = res2_3;
        C3[0] = res3_0;
        C3[1] = res3_1;
        C3[2] = res3_2;
        C3[3] = res3_3;
        C4[0] = res4_0;
        C4[1] = res4_1;
        C4[2] = res4_2;
        C4[3] = res4_3;
        C5[0] = res5_0;
        C5[1] = res5_1;
        C5[2] = res5_2;
        C5[3] = res5_3;
        C6[0] = res6_0;
        C6[1] = res6_1;
        C6[2] = res6_2;
        C6[3] = res6_3;
        C7[0] = res7_0;
        C7[1] = res7_1;
        C7[2] = res7_2;
        C7[3] = res7_3;
        if (!backwards) {
            temp = bk - off;
            temp = left ? temp - 4 : temp - 8;
            ptrba += temp * 4;
            ptrbb += temp * 8;
        }
        C0 = C0 + 4;
        C1 = C1 + 4;
        C2 = C2 + 4;
        C3 = C3 + 4;
        C4 = C4 + 4;
        C5 = C5 + 4;
        C6 = C6 + 4;
        C7 = C7 + 4;
    }
    if (bm & 2) {
        ptrbb = bb;
        res0_0 = 0;
        res0_1 = 0;
        res1_0 = 0;
        res1_1 = 0;
        res2_0 = 0;
        res2_1 = 0;
        res3_0 = 0;
        res3_1 = 0;
        res4_0 = 0;
        res4_1 = 0;
        res5_0 = 0;
        res5_1 = 0;
        res6_0 = 0;
        res6_1 = 0;
        res7_0 = 0;
        res7_1 = 0;
        temp = off + 8;
        for (k = 0; k < temp; k++) {
            b0 = ptrbb[0];
            b1 = ptrbb[1];
            b2 = ptrbb[2];
            b3 = ptrbb[3];
            b4 = ptrbb[4];
            b5 = ptrbb[5];
            b6 = ptrbb[6];
            b7 = ptrbb[7];
            a0 = ptrba[0];
            a1 = ptrba[1];
            float ta0_b0 = a0 * b0, ta0_b1 = a0 * b1, ta0_b2 = a0 * b2, ta0_b3 = a0 * b3;
            float ta0_b4 = a0 * b4, ta0_b5 = a0 * b5, ta0_b6 = a0 * b6, ta0_b7 = a0 * b7;
            res0_0 += ta0_b0;
            res1_0 += ta0_b1;
            res2_0 += ta0_b2;
            res3_0 += ta0_b3;
            res4_0 += ta0_b4;
            res5_0 += ta0_b5;
            res6_0 += ta0_b6;
            res7_0 += ta0_b7;
            res0_1 += a1 * b0;
            res1_1 += a1 * b1;
            res2_1 += a1 * b2;
            res3_1 += a1 * b3;
            res4_1 += a1 * b4;
            res5_1 += a1 * b5;
            res6_1 += a1 * b6;
            res7_1 += a1 * b7;
            ptrba = ptrba + 2;
            ptrbb = ptrbb + 8;
        }
        res0_0 *= alpha;
        res0_1 *= alpha;
        res1_0 *= alpha;
        res1_1 *= alpha;
        res2_0 *= alpha;
        res2_1 *= alpha;
        res3_0 *= alpha;
        res3_1 *= alpha;
        res4_0 *= alpha;
        res4_1 *= alpha;
        res5_0 *= alpha;
        res5_1 *= alpha;
        res6_0 *= alpha;
        res6_1 *= alpha;
        res7_0 *= alpha;
        res7_1 *= alpha;
        C0[0] = res0_0;
        C0[1] = res0_1;
        C1[0] = res1_0;
        C1[1] = res1_1;
        C2[0] = res2_0;
        C2[1] = res2_1;
        C3[0] = res3_0;
        C3[1] = res3_1;
        C4[0] = res4_0;
        C4[1] = res4_1;
        C5[0] = res5_0;
        C5[1] = res5_1;
        C6[0] = res6_0;
        C6[1] = res6_1;
        C7[0] = res7_0;
        C7[1] = res7_1;
        temp = bk - off;
        temp -= 8;
        ptrba += temp * 2;
        ptrbb += temp * 8;
        C0 = C0 + 2;
        C1 = C1 + 2;
        C2 = C2 + 2;
        C3 = C3 + 2;
        C4 = C4 + 2;
        C5 = C5 + 2;
        C6 = C6 + 2;
        C7 = C7 + 2;
    }
    if (bm & 1) {
        ptrbb = bb;
        res0_0 = 0;
        res1_0 = 0;
        res2_0 = 0;
        res3_0 = 0;
        res4_0 = 0;
        res5_0 = 0;
        res6_0 = 0;
        res7_0 = 0;
        temp = off + 8;
        for (k = 0; k < temp; k++) {
            b0 = ptrbb[0];
            b1 = ptrbb[1];
            b2 = ptrbb[2];
            b3 = ptrbb[3];
            b4 = ptrbb[4];
            b5 = ptrbb[5];
            b6 = ptrbb[6];
            b7 = ptrbb[7];
            a0 = ptrba[0];
            res0_0 += a0 * b0;
            res1_0 += a0 * b1;
            res2_0 += a0 * b2;
            res3_0 += a0 * b3;
            res4_0 += a0 * b4;
            res5_0 += a0 * b5;
            res6_0 += a0 * b6;
            res7_0 += a0 * b7;
            ptrba = ptrba + 1;
            ptrbb = ptrbb + 8;
        }
        res0_0 *= alpha;
        res1_0 *= alpha;
        res2_0 *= alpha;
        res3_0 *= alpha;
        res4_0 *= alpha;
        res5_0 *= alpha;
        res6_0 *= alpha;
        res7_0 *= alpha;
        C0[0] = res0_0;
        C1[0] = res1_0;
        C2[0] = res2_0;
        C3[0] = res3_0;
        C4[0] = res4_0;
        C5[0] = res5_0;
        C6[0] = res6_0;
        C7[0] = res7_0;
        temp = bk - off;
        temp -= 8;
        ptrba += temp * 1;
        ptrbb += temp * 8;
        C0 = C0 + 1;
        C1 = C1 + 1;
        C2 = C2 + 1;
        C3 = C3 + 1;
        C4 = C4 + 1;
        C5 = C5 + 1;
        C6 = C6 + 1;
        C7 = C7 + 1;
    }
    k = (bk << 3);
    bb = bb + k;
    i = (ldc << 3);
    C = C + i;
}
}
