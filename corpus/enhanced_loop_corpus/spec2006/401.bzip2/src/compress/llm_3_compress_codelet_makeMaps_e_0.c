// Variable name mappings to avoid conflicts with system symbols



void loop(){
    // Variant 2: Strided memory access with step size of 4
    // Access elements in a non-sequential, strided manner to simulate different cache behavior.
    // We break the loop into multiple passes with stride 4 to cover all indices.
    // This changes spatial locality and may affect performance on systems with cache line optimizations.

    s->nInUse = 0;
    // Process indices in strided order: 0, 4, 8, ..., 1, 5, 9, ..., etc.
    for (Int32 stride = 0; stride < 4; stride++) {
        for (i = stride; i < 256; i += 4) {
            if (s->inUse[i]) {
                s->unseqToSeq[i] = s->nInUse;
                s->nInUse++;
            }
        }
    }
}
