typedef double MagickDoubleType;

typedef MagickDoubleType MagickRealType;

typedef struct _KernelInfo {
    KernelInfoType type;
    size_t width;
    size_t height;
    ssize_t x;
    ssize_t y;
    MagickRealType *values;
    double minimum;
    double maximum;
    double negative_range;
    double positive_range;
    double angle;
    struct _KernelInfo *next;
    size_t signature;
} KernelInfo;

extern KernelInfo *kernel_info;
extern ssize_t i;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
    ssize_t total_size = (ssize_t)(kernel_info->width * kernel_info->height);
    for (i = 0; i < total_size; i += 4) {
        kernel_info->values[i] = (-1.);
        if (i + 1 < total_size) kernel_info->values[i + 1] = (-1.);
        if (i + 2 < total_size) kernel_info->values[i + 2] = (-1.);
        if (i + 3 < total_size) kernel_info->values[i + 3] = (-1.);
    }
}
