typedef double MagickDoubleType;

typedef MagickDoubleType MagickRealType;

typedef struct _KernelInfo {
    KernelInfoType type;
    size_t width;
    size_t height;
    ssize_t x;
    ssize_t y;
    MagickRealType *values;
    double minimum;
    double maximum;
    double negative_range;
    double positive_range;
    double angle;
    struct _KernelInfo *next;
    size_t signature;
} KernelInfo;

extern KernelInfo *kernel;
extern ssize_t i;
extern ssize_t j;
extern ssize_t x;
extern ssize_t y;
extern MagickRealType *k;
extern MagickRealType t;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
    ssize_t width = (ssize_t)kernel->width;
    ssize_t height = (ssize_t)kernel->height;
    ssize_t area = width * height;
    for (i = 0; i < area; i++) {
        ssize_t i1 = i;
        ssize_t i2 = area - i - 1;
        if (i1 >= i2) break;
        t = k[i1];
        k[i1] = k[i2];
        k[i2] = t;
    }
}
