typedef double MagickDoubleType;

typedef MagickDoubleType MagickRealType;

typedef struct _KernelInfo {
    KernelInfoType type;
    size_t width;
    size_t height;
    ssize_t x;
    ssize_t y;
    MagickRealType *values;
    double minimum;
    double maximum;
    double negative_range;
    double positive_range;
    double angle;
    struct _KernelInfo *next;
    size_t signature;
} KernelInfo;

extern double gamma;
extern KernelInfo *kernel_info;
extern ssize_t j;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
    if (kernel_info->width > 0 && kernel_info->height > 0) {
        j = 0;
        for (ssize_t block = 0; block < (ssize_t)(kernel_info->width * kernel_info->height); block += 8) {
            for (ssize_t step = 0; step < 8; step++) {
                ssize_t idx = block + step;
                if (idx >= (ssize_t)(kernel_info->width * kernel_info->height)) break;
                kernel_info->values[idx] *= gamma;
            }
        }
    }
}
