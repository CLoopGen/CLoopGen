typedef double MagickDoubleType;

typedef MagickDoubleType MagickRealType;

typedef struct _KernelInfo {
    KernelInfoType type;
    size_t width;
    size_t height;
    ssize_t x;
    ssize_t y;
    MagickRealType *values;
    double minimum;
    double maximum;
    double negative_range;
    double positive_range;
    double angle;
    struct _KernelInfo *next;
    size_t signature;
} KernelInfo;

extern double gamma;
extern KernelInfo *kernel_info;
extern ssize_t j;

// Variable name mappings to avoid conflicts with system symbols



void loop() {
    ssize_t size = (ssize_t)(kernel_info->width * kernel_info->height);
    MagickRealType* values = kernel_info->values;
    
    // Introduce loop-carried dependency: each iteration depends on the previous value
    // This creates a WAW (Write-After-Write) and converts independent updates into a chain
    if (size > 0) {
        values[0] *= gamma;
        for (j = 1; j < size; j++) {
            values[j] = values[j - 1] + (values[j] * gamma - values[j - 1]);
        }
    }
}
