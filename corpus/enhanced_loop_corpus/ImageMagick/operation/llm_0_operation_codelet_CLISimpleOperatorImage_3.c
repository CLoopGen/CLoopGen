typedef double MagickDoubleType;

typedef MagickDoubleType MagickRealType;

typedef struct _KernelInfo {
    KernelInfoType type;
    size_t width;
    size_t height;
    ssize_t x;
    ssize_t y;
    MagickRealType *values;
    double minimum;
    double maximum;
    double negative_range;
    double positive_range;
    double angle;
    struct _KernelInfo *next;
    size_t signature;
} KernelInfo;

extern double gamma;
extern KernelInfo *kernel_info;
extern ssize_t j;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
    for (ssize_t i = 0; i < (ssize_t)kernel_info->height; i++) {
        for (j = 0; j < (ssize_t)kernel_info->width; j++) {
            kernel_info->values[i * kernel_info->width + j] *= gamma;
        }
    }
}
