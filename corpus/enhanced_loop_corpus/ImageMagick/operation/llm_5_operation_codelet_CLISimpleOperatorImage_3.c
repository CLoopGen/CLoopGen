typedef double MagickDoubleType;

typedef MagickDoubleType MagickRealType;

typedef struct _KernelInfo {
    KernelInfoType type;
    size_t width;
    size_t height;
    ssize_t x;
    ssize_t y;
    MagickRealType *values;
    double minimum;
    double maximum;
    double negative_range;
    double positive_range;
    double angle;
    struct _KernelInfo *next;
    size_t signature;
} KernelInfo;

extern double gamma;
extern KernelInfo *kernel_info;
extern ssize_t j;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
    ssize_t total_elements = (ssize_t)(kernel_info->width * kernel_info->height);
    for (j = 0; j < total_elements; j++) {
        if (kernel_info->values[j] > 0.0) {
            kernel_info->values[j] *= gamma;
        } else {
            kernel_info->values[j] = 0.0;
        }
    }
}
