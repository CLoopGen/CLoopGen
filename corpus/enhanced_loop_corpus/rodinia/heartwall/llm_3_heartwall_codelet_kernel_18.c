void loop(){
    // Variant 2: Strided Memory Access with Indirect Indexing
    // Use indirect array indexing via precomputed offsets to simulate strided access.
    // Introduce a stride pointer that jumps through d_in and d_frame with non-unit strides.
    int *row_indices = private.d_tRowLoc; // Assume d_tRowLoc holds precomputed relative row offsets
    int *col_indices = private.d_tColLoc; // Assume d_tColLoc holds precomputed relative col offsets
    float alpha = public.alpha;
    float one_minus_alpha = 1.0f - alpha;
    int base_row = private.d_Row[private.point_no] - 26;
    int base_col = private.d_Col[private.point_no] - 26;
    int in_idx, frame_idx;

    for (col = 0; col < public.in_mod_cols; col++) {
        int c_offset = col_indices[col]; // Indirect column offset
        for (row = 0; row < public.in_mod_rows; row++) {
            int r_offset = row_indices[row]; // Indirect row offset
            in_idx = col * public.in_mod_rows + row;
            frame_idx = (base_col + c_offset) * public.frame_rows + (base_row + r_offset);
            d_in[in_idx] = alpha * d_in[in_idx] + one_minus_alpha * public.d_frame[frame_idx];
        }
    }
}
