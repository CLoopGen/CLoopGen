extern AVPacket *pkt;
extern uint32_t *flags;
extern uint32_t c;
extern int i;
extern int closed_gop;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
    uint32_t local_c = c;
    int local_closed_gop = closed_gop;
    int exit_flag = 0;
    for (i = 0; i < pkt->size - 4 && !exit_flag; i++) {
        local_c = (local_c << 8) + pkt->data[i];
        if (local_c == 440) {
            local_closed_gop = pkt->data[i + 4] >> 6 & 1;
        } else if (local_c == 256) {
            int temp_ref = (pkt->data[i + 1] << 2) | (pkt->data[i + 2] >> 6);
            if (!temp_ref || local_closed_gop)
                *flags = 1;
            else
                *flags = 2;
            exit_flag = 1;
        }
    }
    c = local_c;
    closed_gop = local_closed_gop;
}
