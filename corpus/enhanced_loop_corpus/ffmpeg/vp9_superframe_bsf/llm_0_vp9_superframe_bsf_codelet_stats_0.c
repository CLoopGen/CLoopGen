typedef struct AVPacket {
    AVBufferRef *buf;
    int64_t pts;
    int64_t dts;
    uint8_t *data;
    int size;
    int stream_index;
    int flags;
    AVPacketSideData *side_data;
    int side_data_elems;
    int64_t duration;
    int64_t pos;
    int64_t convergence_duration __attribute__((deprecated("")));
} AVPacket;

extern AVPacket * *in;
extern int n_in;
extern int n;
extern unsigned int max;
extern unsigned int sum;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
    // Variant 1: Increased loop depth by introducing an inner loop that processes side_data elements
    for (n = 0; n < n_in; n++) {
        unsigned int sz = in[n]->size;
        if (sz > max)
            max = sz;
        sum += sz;

        // Additional nested loop over side_data_elems to simulate deeper traversal
        for (int i = 0; i < in[n]->side_data_elems; i++) {
            unsigned int side_sz = in[n]->side_data[i].size;
            if (side_sz > max)
                max = side_sz;
            sum += side_sz;
        }
    }
}
