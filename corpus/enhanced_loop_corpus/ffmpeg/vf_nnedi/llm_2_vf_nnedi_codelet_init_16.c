extern NNEDIContext *s;
extern float *bdata;
extern int j;
extern int k;
extern double mean[4];
extern double half;

// Variable name mappings to avoid conflicts with system symbols



void loop(){
    // Variant 1: Strided Memory Access Pattern
    // Instead of iterating by j then k, we access memory with a fixed stride across the weights0 and bdata arrays.
    // This variant accesses elements in a column-major-like fashion, improving spatial locality in certain cache scenarios.
    int idx;
    for (k = 0; k < 48; k++) {
        for (j = 0; j < 4; j++) {
            idx = j * 48 + k;
            s->weights0[idx] = (float)((bdata[idx] - mean[j]) / half);
        }
    }
}
