AVPacket *pkt;
AVFrame *frame;
int x;

static uint8_t *packet_data = NULL;
static uint8_t *frame_data_ptr = NULL;
static AVBufferRef packet_buffer = {0};
static AVBufferRef frame_buffers[8] = {0};

void init_vars() {
    const size_t target_data_size = 128 * 1024 * 1024; // ~128 MB for ~0.01 sec runtime on modern CPU
    const int estimated_width = 1920;
    const int estimated_height = (target_data_size / 2) / estimated_width;
    const int total_size = estimated_width * estimated_height * 2;

    packet_data = (uint8_t*)calloc(total_size, sizeof(uint8_t));
    frame_data_ptr = (uint8_t*)calloc(estimated_width * estimated_height * 3 / 2, sizeof(uint8_t));

    if (!packet_data || !frame_data_ptr) {
        fprintf(stderr, "Memory allocation failed\n");
        exit(1);
    }

    pkt = (AVPacket*)calloc(1, sizeof(AVPacket));
    frame = (AVFrame*)calloc(1, sizeof(AVFrame));

    if (!pkt || !frame) {
        fprintf(stderr, "Memory allocation failed\n");
        exit(1);
    }

    pkt->buf = &packet_buffer;
    pkt->data = packet_data;
    pkt->size = total_size;
    pkt->stream_index = 0;
    pkt->flags = 0;
    pkt->side_data = NULL;
    pkt->side_data_elems = 0;
    pkt->pts = 0;
    pkt->dts = 0;
    pkt->duration = 0;
    pkt->pos = -1;

    frame->data[0] = frame_data_ptr;
    frame->width = estimated_width;
    frame->height = estimated_height;
    frame->nb_samples = 0;
    frame->format = 0;
    frame->key_frame = 1;
    frame->pict_type = AV_PICTURE_TYPE_I;
    frame->linesize[0] = estimated_width;
    frame->sample_aspect_ratio.num = 1;
    frame->sample_aspect_ratio.den = 1;
    frame->pts = 0;
    frame->pkt_dts = 0;
    frame->coded_picture_number = 0;
    frame->display_picture_number = 0;
    frame->quality = 0;
    frame->repeat_pict = 0;
    frame->interlaced_frame = 0;
    frame->top_field_first = 0;
    frame->palette_has_changed = 0;
    frame->reordered_opaque = 0;
    frame->sample_rate = 0;
    frame->channel_layout = 0;
    frame->buf[0] = &frame_buffers[0];
    frame->extended_buf = NULL;
    frame->nb_extended_buf = 0;
    frame->side_data = NULL;
    frame->nb_side_data = 0;
    frame->flags = 0;
    frame->color_range = AVCOL_RANGE_MPEG;
    frame->color_primaries = AVCOL_PRI_BT709;
    frame->color_trc = AVCOL_TRC_BT709;
    frame->colorspace = AVCOL_SPC_BT709;
    frame->chroma_location = AVCHROMA_LOC_CENTER;
    frame->best_effort_timestamp = 0;
    frame->pkt_pos = -1;
    frame->pkt_duration = 0;
    frame->metadata = NULL;
    frame->decode_error_flags = 0;
    frame->channels = 0;
    frame->pkt_size = 0;
    frame->hw_frames_ctx = NULL;
    frame->opaque_ref = NULL;
    frame->crop_top = 0;
    frame->crop_bottom = 0;
    frame->crop_left = 0;
    frame->crop_right = 0;
    frame->private_ref = NULL;
}