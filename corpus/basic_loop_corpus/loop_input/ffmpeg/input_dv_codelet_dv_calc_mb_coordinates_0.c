typedef struct AVDVProfile {
    int dsf;
    int video_stype;
    int frame_size;
    int difseg_size;
    int n_difchan;
    AVRational time_base;
    int ltc_divisor;
    int height;
    int width;
    AVRational sar[2];
    enum AVPixelFormat pix_fmt;
    int bpm;
    const uint8_t *block_sizes;
    int audio_stride;
    int audio_min_samples[3];
    int audio_samples_dist[5];
    const uint8_t (*audio_shuffle)[9];
} AVDVProfile;

AVDVProfile *d;
int chan;
int seq;
int slot;
uint16_t *tbl;
uint8_t off[5] = {0, 1, 2, 3, 4};
uint8_t shuf1[5] = {0, 1, 2, 3, 4};
uint8_t shuf2[5] = {0, 1, 2, 3, 4};
uint8_t shuf3[5] = {0, 1, 2, 3, 4};
uint8_t l_start[10] = {0, 3, 6, 9, 12, 15, 18, 21, 24, 27};
uint8_t l_start_shuffled[5] = {0, 1, 2, 3, 4};
uint8_t serpent1[27] = {0};
uint8_t serpent2[27] = {0};
uint8_t remap[100][2] = {{0}};

int i;
int k;
int m;
int x;
int y;
int blk;

void init_vars() {
    d = (AVDVProfile*)calloc(1, sizeof(AVDVProfile));
    d->width = 1440;
    d->pix_fmt = AV_PIX_FMT_YUV422P;
    d->difseg_size = 15;
    d->height = 1080;

    chan = 0;
    seq = 0;
    slot = 0;

    tbl = (uint16_t*)calloc(5, sizeof(uint16_t));

    for (int idx = 0; idx < 10; idx++) {
        l_start[idx] = idx * 3;
    }
    for (int idx = 0; idx < 5; idx++) {
        shuf1[idx] = idx * 2;
        shuf2[idx] = idx * 3;
        shuf3[idx] = idx * 4;
        l_start_shuffled[idx] = idx + 10;
    }
    for (int idx = 0; idx < 27; idx++) {
        serpent1[idx] = idx * 2;
        serpent2[idx] = idx * 3;
    }
    for (int idx = 0; idx < 100; idx++) {
        remap[idx][0] = idx % 80;
        remap[idx][1] = idx;
    }

    off[0] = 0; off[1] = 1; off[2] = 2; off[3] = 3; off[4] = 4;
}