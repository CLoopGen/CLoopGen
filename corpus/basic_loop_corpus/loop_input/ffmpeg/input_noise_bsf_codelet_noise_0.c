typedef struct NoiseContext {
    const AVClass *class;
    int amount;
    int dropamount;
    unsigned int state;
} NoiseContext;

AVPacket *pkt;
NoiseContext *s;
int amount;
int i;

static uint8_t *packet_data = NULL;
static AVBufferRef buffer_ref;
static AVPacket static_pkt;
static NoiseContext static_s;
static AVClass noise_class = {
    .class_name = "noise",
    .item_name = NULL,
    .option = NULL,
    .version = 0,
    .log_level_offset_offset = 0,
    .parent_log_context_offset = 0,
    .child_next = NULL,
    .child_class_next = NULL,
    .category = AV_CLASS_CATEGORY_FILTER,
    .get_category = NULL,
    .query_ranges = NULL
};

void init_vars() {
    const size_t data_size = 131072; // ~131KB for ~0.01 sec runtime estimate

    packet_data = (uint8_t *)calloc(data_size, sizeof(uint8_t));
    if (!packet_data) exit(1);

    for (size_t j = 0; j < data_size; j++) {
        packet_data[j] = (uint8_t)(j & 0xFF);
    }

    buffer_ref.buffer = NULL;
    buffer_ref.data = packet_data;
    buffer_ref.size = data_size;

    static_pkt.buf = &buffer_ref;
    static_pkt.pts = 0;
    static_pkt.dts = 0;
    static_pkt.data = packet_data;
    static_pkt.size = data_size;
    static_pkt.stream_index = 0;
    static_pkt.flags = 0;
    static_pkt.side_data = NULL;
    static_pkt.side_data_elems = 0;
    static_pkt.duration = 0;
    static_pkt.pos = -1;
    static_pkt.convergence_duration = 0;

    pkt = &static_pkt;

    static_s.class = &noise_class;
    static_s.amount = 100;
    static_s.dropamount = 0;
    static_s.state = 12345;

    s = &static_s;
    amount = 100;
    i = 0;
}