void init_vars() {
    size_t size_a = (size_t)bm * bk;
    size_t size_b = (size_t)bk * bn;
    size_t size_c = (size_t)ldc * bn;

    ba = (float*)aligned_alloc(64, size_a * sizeof(float));
    bb = (float*)aligned_alloc(64, size_b * sizeof(float));
    C = (float*)aligned_alloc(64, size_c * sizeof(float));

    if (!ba || !bb || !C) {
        fprintf(stderr, "Allocation failed\n");
        exit(1);
    }

    for (size_t i = 0; i < size_a; i++) ba[i] = (float)((i % 17) * 0.1);
    for (size_t i = 0; i < size_b; i++) bb[i] = (float)((i % 19) * 0.05);
    for (size_t i = 0; i < size_c; i++) C[i] = 0.0f;
}